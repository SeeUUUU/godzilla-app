/**
 * 특정 스테이지(1~12)에 해당하는 10개 수학 문제를 반환합니다.
 * 범위를 벗어날 경우 12로 모듈러 연산하여 순환합니다.
 */
export const getMathProblemsForStage = (stageNum: number): MathProblemItem[] => {
  const normalizedStage = ((stageNum - 1) % TOTAL_MATH_STAGES) + 1;
  const filtered = MATH_PROBLEMS.filter((p) => p.stage === normalizedStage);
  if (filtered.length >= PROBLEMS_PER_MATH_STAGE) {
    return filtered.slice(0, PROBLEMS_PER_MATH_STAGE);
  }
  return MATH_PROBLEMS.slice(0, PROBLEMS_PER_MATH_STAGE);
};
